/** The zone whose calendar decides an event's date. The meetup is held in New York. */
export function eventTimeZone(): string {
  return process.env.EVENT_TIME_ZONE ?? "America/New_York";
}

/** The calendar date (YYYY-MM-DD) that `instant` falls on in `timeZone`. Throws on an unknown zone. */
export function calendarDate(instant: Date, timeZone: string): string {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(instant);
  const part = (type: string) => parts.find((entry) => entry.type === type)?.value;
  return `${part("year")}-${part("month")}-${part("day")}`;
}

export function isCalendarDate(value: string): boolean {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const parsed = new Date(`${value}T00:00:00Z`);
  return !Number.isNaN(parsed.getTime()) && parsed.toISOString().slice(0, 10) === value;
}
